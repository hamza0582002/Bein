let current = 'ar';

export function setLanguage(lang) {
  current = strings[lang] ? lang : 'ar';
  document.documentElement.lang = current;
  document.documentElement.dir = current === 'ar' ? 'rtl' : 'ltr';
}

export const getLanguage = () => current;
export const isRTL = () => current === 'ar';

/** Translate a key; unknown keys fall back to the key itself. */
export function t(key, vars) {
  let text = strings[current]?.[key] ?? strings.ar[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, value);
    }
  }
  return text;
}

/** Locale-aware number formatting (Arabic keeps Western digits — easier to scan). */
export const n = (value) => new Intl.NumberFormat(current === 'ar' ? 'ar-EG-u-nu-latn' : 'en').format(value);
